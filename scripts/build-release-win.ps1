#Requires -Version 5.1
<#
DuduAI Workbench V1.3 Windows x64 NSIS RELEASE BUILDER.
Never deploys Cloudflare, never creates production license keys, never changes userData.
Creates an ephemeral source-only copy and mutates only that copy.
#>
[CmdletBinding()]
param(
  [switch]$CheckOnly,
  [switch]$KeepBuild,
  [string]$LicenseUrl = $env:DUDU_LICENSE_URL,
  [string]$PublicKey = $env:DUDU_LICENSE_PUBLIC_KEY_B64,
  [string]$FfmpegUrl = $env:DUDU_FFMPEG_ZIP_URL,
  [string]$FfmpegSha256 = $env:DUDU_FFMPEG_ZIP_SHA256
)
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
$sourceRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$sourceRoot = $sourceRoot.TrimEnd('\')
$releaseDir = Join-Path $sourceRoot 'release'
$logsDir = Join-Path $sourceRoot 'build-logs'
$stage = $null
$transcriptStarted = $false
$success = $false

function Fail([string]$message) { throw "[DUDU RELEASE] $message" }
function Run-Checked([string]$executable,[string[]]$arguments) {
  Write-Host ("[EXEC] {0} {1}" -f (Split-Path $executable -Leaf),($arguments -join ' '))
  & $executable @arguments
  if ($LASTEXITCODE -ne 0) { Fail ("Command failed with code {0}: {1}" -f $LASTEXITCODE,(Split-Path $executable -Leaf)) }
}
function Command-Path([string]$name) {
  $c = Get-Command $name -ErrorAction SilentlyContinue
  if (-not $c) { Fail ("Missing build tool: {0}. Install it on the build computer (NOT on customer computers)." -f $name) }
  return $c.Source
}
function Copy-BuildTree([string]$from,[string]$to) {
  if (-not (Test-Path -LiteralPath $from -PathType Container)) { Fail ('Missing source directory: '+$from) }
  $blocked = @('node_modules','.git','.private','.wrangler','release','build','dist','build-logs','target','.venv','__pycache__','Cookies','User Data','test-state')
  foreach ($item in (Get-ChildItem -LiteralPath $from -Recurse -Force -File)) {
    $rel = $item.FullName.Substring($from.Length).TrimStart([char[]]@('\','/'))
    $pieces = $rel -split '[\\/]'
    $skip = $false
    foreach ($p in $pieces) { if ($blocked -contains $p) { $skip = $true; break } }
    if ($skip) { continue }
    if ($item.Name -match '^(?:\.dev\.vars(?:\..*)?|\.env(?:\..*)?|owner-keys\.json|test-owner-keys\.json|wrangler\.local\.toml|workspace\.json|config\.json|license-config\.local\.json|notice-cache\.json|download-settings\.json|voice-bindings\.json)$' -or
        $item.Name -match '\.(?:exe|dll|node|pfx|pem|key|sqlite|sqlite3|db|log|tmp)$') { continue }
    $dest = Join-Path $to $rel
    New-Item -ItemType Directory -Path (Split-Path -Parent $dest) -Force | Out-Null
    Copy-Item -LiteralPath $item.FullName -Destination $dest -Force
  }
}
function Copy-SafeFile([string]$relative) {
  $from = Join-Path $sourceRoot $relative
  $to = Join-Path $stage $relative
  if (-not (Test-Path -LiteralPath $from -PathType Leaf)) { Fail ('Missing source file '+$relative) }
  New-Item -ItemType Directory -Path (Split-Path -Parent $to) -Force | Out-Null
  Copy-Item -LiteralPath $from -Destination $to -Force
}

try {
  if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT -or -not [Environment]::Is64BitOperatingSystem) {
    Fail 'This build script requires Windows 10/11 x64; users installing the generated EXE do not need development tools.'
  }
  New-Item -ItemType Directory -Path $logsDir -Force | Out-Null
  $logPath=Join-Path $logsDir ("build-{0}.log" -f (Get-Date -Format 'yyyyMMdd-HHmmss'))
  Start-Transcript -Path $logPath | Out-Null
  $transcriptStarted=$true
  Write-Host '============================================='
  Write-Host ' DuduAI Workbench v1.3.0 | Windows NSIS x64'
  Write-Host ' Production D1, Worker, device sessions and license keys are not modified.'
  Write-Host '============================================='
  Set-Location $sourceRoot
  $node=Command-Path 'node.exe';$npm=Command-Path 'npm.cmd'
  $major=[int]((& $node --version).Trim().TrimStart('v').Split('.')[0])
  if ($major -lt 22) { Fail 'Please install Node.js 22 or newer.' }
  Run-Checked $node @('scripts/release-preflight.js')
  Run-Checked $node @('--test','tests/release-package.test.js')
  if ($CheckOnly) {
    Write-Host 'PASS: local source / release identity / script checks. No EXE generated by -CheckOnly.'
    $success=$true
  } else {
    $cargo=Command-Path 'cargo.exe'
    $rustc=Command-Path 'rustc.exe'
    $hostSpec=(& $rustc '-vV' | Select-String '^host:').ToString()
    if ($hostSpec -notmatch 'x86_64-pc-windows-msvc') { Fail ('Rust default host must be x86_64-pc-windows-msvc, actual '+$hostSpec) }
    . (Join-Path $PSScriptRoot 'find-python312.ps1')
    $python = Find-DuduPython312
    if (-not $python) {
      Fail 'Python 3.12 was not found. Run INSTALL_Python312.cmd (requires your explicit YES), then CHECK_Build_Tools.cmd. This is a build PC prerequisite only.'
    }
    $pythonExe=[string]$python.Executable
    $pythonBase=@($python.Arguments)
    Write-Host ('[PYTHON 3.12] '+$pythonExe+' '+($pythonBase -join ' '))
    if (-not $LicenseUrl -or -not $PublicKey) {
      Write-Warning 'Only PUBLIC settings are requested. Never enter admin tokens, merchant secrets or Ed25519 private keys.'
      if (-not $LicenseUrl) { $LicenseUrl = Read-Host 'Official Cloudflare Worker HTTPS base URL' }
      if (-not $PublicKey) { $PublicKey = Read-Host 'Original Ed25519 PUBLIC verification key (base64 SPKI)' }
    }
    if (-not $LicenseUrl -or -not $PublicKey) { Fail 'Missing required production Worker URL or Ed25519 public key. Cannot create a publicly shareable installer.' }
    [uri]$parsed = $null
    if (-not [uri]::TryCreate($LicenseUrl,[UriKind]::Absolute,[ref]$parsed) -or
        $parsed.Scheme -ne 'https' -or $parsed.Port -ne 443 -or
        $parsed.UserInfo -or $parsed.Query -or $parsed.Fragment -or
        $parsed.AbsolutePath -ne '/' -or $parsed.Host -match '^(?:localhost|127\.|10\.|192\.168\.|169\.254\.|172\.(?:1[6-9]|2\d|3[01])\.)') {
      Fail 'Release license URL must be a clean public HTTPS root, never the local 127.0.0.1 test Worker.'
    }
    if ($PublicKey -notmatch '^[A-Za-z0-9+/]{50,150}={0,2}$') { Fail 'Invalid Ed25519 public verification key format.' }
    $env:DUDU_LICENSE_URL=$LicenseUrl
    $env:DUDU_LICENSE_PUBLIC_KEY_B64=$PublicKey
    $env:CSC_IDENTITY_AUTO_DISCOVERY='false' # Do not silently sign using an unexpected local certificate.
    # Edge follows the current Windows user proxy, while Node and curl normally
    # connect directly. Resolve that same system route before any dependency
    # downloads; never copy browser cookies or weaken TLS verification.
    if (-not $env:HTTPS_PROXY -and -not $env:https_proxy -and
        -not $env:HTTP_PROXY -and -not $env:http_proxy) {
      $attestUri=[uri]($parsed.GetLeftPart([UriPartial]::Authority)+'/v1/license/attest')
      $systemProxy=[System.Net.WebRequest]::GetSystemWebProxy().GetProxy($attestUri)
      if ($systemProxy -and $systemProxy.AbsoluteUri -ne $attestUri.AbsoluteUri) {
        if ($systemProxy.Scheme -notin @('http','https') -or $systemProxy.UserInfo -or
            -not $systemProxy.Host -or $systemProxy.Port -lt 1) {
          Fail 'Windows system proxy for the authorization Worker is not a usable HTTP(S) proxy.'
        }
        $env:HTTPS_PROXY=$systemProxy.GetLeftPart([UriPartial]::Authority)
        Write-Host '[BUILD NETWORK] Using the current Windows user HTTPS proxy (address redacted).'
      }
    }
    if ($env:HTTPS_PROXY -or $env:https_proxy -or $env:HTTP_PROXY -or $env:http_proxy) {
      $env:NODE_USE_ENV_PROXY='1'
      Write-Host '[BUILD NETWORK] Downloads and authorization requests will use the configured proxy.'
    }
    $stage=Join-Path $env:TEMP ('DuduAI-Release-v1.3.0-'+[Guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $stage -Force | Out-Null
    Write-Host ('[STAGING] '+$stage)
    foreach($directory in @('src','scripts','tests','assets','native-core','docs')) {
      Copy-BuildTree (Join-Path $sourceRoot $directory) (Join-Path $stage $directory)
    }
    foreach($directory in @('src','scripts','tests')) {
      Copy-BuildTree (Join-Path $sourceRoot ('license-service/'+$directory)) (Join-Path $stage ('license-service/'+$directory))
    }
    Copy-BuildTree (Join-Path $sourceRoot 'cloud-content/src') (Join-Path $stage 'cloud-content/src')
    foreach($file in @('package.json','package-lock.json','release-build.json',
      'license-service/package.json','license-service/package-lock.json','license-service/schema.sql',
      # The legacy Chinese-named one-click launcher remains in the original archive.
      # It is not needed in the staging build tree, and PowerShell 5.1 without a UTF-8 BOM
      # misreads literal Chinese strings using the system ANSI code page.
      'REPAIR_Electron.cmd','START_DUDUAI_LOCAL_TEST.bat','BUILD_Windows_EXE.cmd',
      'INSTALL_Python312.cmd')) { Copy-SafeFile $file }
    # The release checks run inside staging. Keep their safe opt-in build helper
    # alongside the staged test suite; electron-builder only packages files
    # listed in release-build.json, so this helper never enters customer EXEs.
    Set-Location $stage
    # Stage is a strictly source-only fresh copy. No original node_modules, .private, user profile or build output.
    if (Test-Path 'license-service/.private') { Fail 'A private credential directory was copied into staging; abort.' }
    if (Test-Path 'license-service/.dev.vars') { Fail 'Cloudflare dev secrets were copied into staging; abort.' }
    Run-Checked $node @('scripts/release-preflight.js')
    # Reproducible installs based on the uploaded lockfiles, never blindly reuse node_modules.
    Run-Checked $npm @('ci','--no-audit','--no-fund')
    # npm >=11 can skip dependency install scripts; use the EXACT pinned
    # electron package install.js, with verified offline ZIP / mirror fallback.
    # Browser-downloaded ZIP is accepted only if its SHA256 matches the
    # official electron/checksums.json packaged with the pinned npm release.
    if (-not $env:DUDU_ELECTRON_ZIP_PATH) {
      $electronVersion=(Get-Content -LiteralPath (Join-Path $stage 'node_modules/electron/package.json') -Raw | ConvertFrom-Json).version
      $zipName=('electron-v'+$electronVersion+'-win32-x64.zip')
      $candidate=Join-Path $sourceRoot $zipName
      if (Test-Path -LiteralPath $candidate -PathType Leaf) {
        $env:DUDU_ELECTRON_ZIP_PATH=$candidate
      }
    }
    Run-Checked $node @('scripts/ensure-electron-win.js')
    Run-Checked $npm @('run','brand:generate')
    Run-Checked $npm @('run','installer:art')
    Run-Checked $npm @('run','check')
    Run-Checked $npm @('run','release:check')
    Run-Checked $npm @('run','license:check')
    Write-Host '[AUTH] Verifying REAL remote Worker Ed25519 attestation before producing release artifacts.'
    Run-Checked $npm @('run','license:prepare')
    Run-Checked $node @('scripts/prepare-public-notice.js')
    Run-Checked $node @('scripts/prepare-feed.js')
    # Keep 12 real, red-circled screenshots from the actual workbench UI. No synthetic static substitutes.
    Run-Checked $pythonExe ($pythonBase+@('-m','pip','install','playwright','Pillow','--disable-pip-version-check'))
    Run-Checked $pythonExe ($pythonBase+@('-m','playwright','install','chromium'))
    Run-Checked $pythonExe ($pythonBase+@('scripts/generate-tutorial-screenshots.py'))
    if (@(Get-ChildItem 'assets/tutorial' -File -Filter 'step-*.webp').Count -ne 12) { Fail 'Tutorial screenshot generation incomplete.' }
    Run-Checked $cargo @('test','--locked','--manifest-path','native-core/Cargo.toml')
    Run-Checked $cargo @('build','--locked','--manifest-path','native-core/Cargo.toml','--release')
    $nativeDll=Join-Path $stage 'native-core/target/release/dudu_core.dll'
    if (-not (Test-Path -LiteralPath $nativeDll -PathType Leaf) -or (Get-Item $nativeDll).Length -lt 10000) { Fail 'Rust native addon DLL was not compiled.' }
    New-Item -ItemType Directory -Path 'native' -Force | Out-Null
    Copy-Item -LiteralPath $nativeDll -Destination 'native/dudu_core.node' -Force
    # Pin the LGPL archive to the publisher's versioned release and published
    # checksums.sha256 entry. A caller-supplied URL must also supply its digest.
    if (-not $FfmpegUrl) {
      $FfmpegUrl='https://github.com/BtbN/FFmpeg-Builds/releases/download/autobuild-2026-11-15-12-40/ffmpeg-N-128915-g3d16b774d7-win64-lgpl.zip'
      if (-not $FfmpegSha256) { $FfmpegSha256='bc39b32bbcb56c0dd679e69a37e63cfce88b911240946cccfe966d30f9a279b4' }
    }
    if ($FfmpegUrl -notmatch '^https://github\.com/BtbN/FFmpeg-Builds/releases/download/[A-Za-z0-9._-]+/[A-Za-z0-9._-]+-win64-lgpl\.zip$') {
      Fail 'FFmpeg URL must point to the expected GitHub BtbN LGPL Windows release.'
    }
    if ($FfmpegSha256 -notmatch '^[a-fA-F0-9]{64}$') { Fail 'FFmpeg release requires a trusted SHA-256 digest.' }
    $ffzip=Join-Path $stage 'ffmpeg-lgpl-build.zip'
    $ffdir=Join-Path $stage 'ffmpeg-extract'
    $cacheDir=Join-Path $sourceRoot 'build-cache'
    $cacheZip=Join-Path $cacheDir ('ffmpeg-'+$FfmpegSha256.ToLowerInvariant()+'.zip')
    if (Test-Path -LiteralPath $cacheZip -PathType Leaf) {
      Write-Host '[FFMPEG] Reusing cached LGPL archive after checksum verification.'
      Copy-Item -LiteralPath $cacheZip -Destination $ffzip
    } else {
      Write-Host '[FFMPEG] Fetching pinned LGPL third-party binaries...'
      Invoke-WebRequest -Uri $FfmpegUrl -OutFile $ffzip -MaximumRedirection 10 -UseBasicParsing
    }
    $digest=(Get-FileHash -LiteralPath $ffzip -Algorithm SHA256).Hash.ToLowerInvariant()
    Write-Host ('[FFMPEG] SHA256 '+$digest)
    if ($digest -ne $FfmpegSha256.Trim().ToLowerInvariant()) { Fail 'FFmpeg archive digest does not match expected hash.' }
    if (-not (Test-Path -LiteralPath $cacheZip -PathType Leaf)) {
      New-Item -ItemType Directory -Path $cacheDir -Force | Out-Null
      Copy-Item -LiteralPath $ffzip -Destination $cacheZip
    }
    Expand-Archive -LiteralPath $ffzip -DestinationPath $ffdir -Force
    New-Item -ItemType Directory -Path 'vendor/bin' -Force | Out-Null
    foreach($name in @('ffmpeg.exe','ffprobe.exe')) {
      $bin=Get-ChildItem -LiteralPath $ffdir -File -Recurse -Filter $name | Select-Object -First 1
      if (-not $bin -or $bin.Length -lt 500000) { Fail ('Missing valid Windows binary: '+$name) }
      Copy-Item -LiteralPath $bin.FullName -Destination (Join-Path 'vendor/bin' $name) -Force
      Run-Checked (Join-Path $stage ('vendor/bin/'+$name)) @('-version')
    }
    Invoke-WebRequest -Uri 'https://raw.githubusercontent.com/FFmpeg/FFmpeg/master/COPYING.LGPLv2.1' -OutFile 'vendor/bin/COPYING.LGPLv2.1' -UseBasicParsing
    Copy-Item 'docs/FFMPEG_NOTICE.txt' 'vendor/bin/FFMPEG_NOTICE.txt' -Force
    # All protection happens ONLY in staging, never in user project source.
    Run-Checked $npm @('run','native:replace')
    Run-Checked $npm @('run','native:verify')
    Run-Checked $node @('scripts/harden.js')
    Run-Checked $npm @('run','check:hardened')
    # electron-builder's pinned Windows tool archive also contains macOS
    # symlinks. Extract only Windows-relevant entries so standard Windows users
    # can build without enabling Developer Mode or administrator privileges.
    $builderCache=Join-Path $sourceRoot 'build-cache/electron-builder'
    $winToolCache=Join-Path $builderCache 'winCodeSign'
    $winToolArchive=Join-Path $winToolCache 'winCodeSign-2.6.0.7z'
    New-Item -ItemType Directory -Path $winToolCache -Force | Out-Null
    if (-not (Test-Path -LiteralPath $winToolArchive -PathType Leaf)) {
      Invoke-WebRequest -Uri 'https://github.com/electron-userland/electron-builder-binaries/releases/download/winCodeSign-2.6.0/winCodeSign-2.6.0.7z' -OutFile $winToolArchive -UseBasicParsing
    }
    $toolBytes=[IO.File]::ReadAllBytes($winToolArchive)
    $toolSha512=[Convert]::ToBase64String(([Security.Cryptography.SHA512]::Create().ComputeHash($toolBytes)))
    if ($toolSha512 -ne '6LQI2d9BPC3Xs0ZoTQe1o3tPiA28c7+PY69Q9i/pD8lY45psMtHuLwv3vRckiVr3Zx1cbNyLlBR8STwCdcHwtA==') {
      Fail 'Windows code-sign tool archive does not match publisher SHA-512.'
    }
    $sevenZip=Join-Path $stage 'node_modules/7zip-bin/win/x64/7za.exe'
    $winToolDir=Join-Path $winToolCache 'winCodeSign-2.6.0'
    Run-Checked $sevenZip @('x','-bd','-y','-xr!darwin','-xr!linux',$winToolArchive,('-o'+$winToolDir))
    if (-not (Test-Path -LiteralPath (Join-Path $winToolDir 'rcedit-x64.exe') -PathType Leaf)) {
      Fail 'Verified Windows resource editor is missing from cache.'
    }
    $env:ELECTRON_BUILDER_CACHE=$builderCache
    Run-Checked $node @('--require','./scripts/retry-electron-integrity-write.cjs',
      'node_modules/electron-builder/cli.js','--win','nsis','--x64','--config','release-build.json','--publish','never')
    Run-Checked $npm @('run','verify:release')
    Run-Checked $npm @('run','release:guard')
    $exe=Join-Path $stage 'release/DuduAI-Workbench-Setup-v1.3.0-x64.exe'
    if (-not (Test-Path -LiteralPath $exe -PathType Leaf) -or (Get-Item $exe).Length -lt 15000000) { Fail 'Installer was not generated or is unusually small.' }
    New-Item -ItemType Directory -Path $releaseDir -Force | Out-Null
    $out=Join-Path $releaseDir 'DuduAI-Workbench-Setup-v1.3.0-x64.exe'
    Copy-Item -LiteralPath $exe -Destination $out -Force
    $hash=(Get-FileHash -LiteralPath $out -Algorithm SHA256).Hash.ToLowerInvariant()
    Set-Content -LiteralPath (Join-Path $releaseDir 'SHA256SUMS.txt') -Value ($hash+'  DuduAI-Workbench-Setup-v1.3.0-x64.exe') -Encoding ASCII
    $signature=Get-AuthenticodeSignature -LiteralPath $out
    Write-Host ('[SIGNATURE] '+$signature.Status)
    if ($signature.Status -ne 'Valid') { Write-Warning 'Windows EXE is NOT code-signed; SmartScreen may warn. Obtain a real Windows code-signing certificate for public distribution.' }
    $note=@(
      'DuduAI Workbench V1.3 Windows x64',
      'Install by double clicking DuduAI-Workbench-Setup-v1.3.0-x64.exe.',
      'Installer is configured to retain existing user data on upgrade/uninstall; verify on an isolated Windows test profile before public rollout.',
      'AppData: %APPDATA%\\DoubaoCreativeHubPublic',
      'Remote licensing requires Internet and the original official license Worker.',
      'Backend, local test credentials, user cookies and projects are NOT included.',
      ("Windows installer Authenticode status: {0}" -f $signature.Status),
      ("FFmpeg source archive SHA256: {0}" -f $digest)
    )
    Set-Content -LiteralPath (Join-Path $releaseDir 'RELEASE_NOTES.txt') -Value $note -Encoding UTF8
    Write-Host '[DONE] Real installer copied to: ' $out
    Write-Host '[DONE] SHA256: ' $hash
    $success=$true
  }
} catch {
  Write-Host ('[BUILD FAILED] '+$_.Exception.Message) -ForegroundColor Red
  Write-Host ('[DIAGNOSTICS] '+$logsDir)
} finally {
  Set-Location $sourceRoot
  if ($transcriptStarted) { Stop-Transcript | Out-Null }
  if ($stage -and -not $KeepBuild -and $success) {
    try { Remove-Item -LiteralPath $stage -Force -Recurse -ErrorAction Stop }
    catch { Write-Warning ('Could not remove temporary stage: '+$stage) }
  } elseif ($stage -and -not $success) {
    Write-Host ('[DEBUG STAGING KEPT] '+$stage)
    Write-Host 'Delete the temporary staging folder manually after error diagnosis; it contains source files and public license configuration only.'
  }
}
if (-not $success) { exit 1 }
exit 0
