// M2: embed official domestic AI pages in the EXISTING Tauri main window.
// Apply after all legacy overlays and v4 M1; fail closed on upstream drift.
import fs from 'node:fs';
import path from 'node:path';

const root=path.resolve(process.argv[2]||'.');
const overlay=path.resolve(process.argv[3]||'desktop-overlay');
const staged=new Map();
function patch(file,from,to){
  const content=(staged.get(file)??fs.readFileSync(path.join(root,file),'utf8')).replace(/\r\n/g,'\n');
  if(!content.includes(from)||content.includes(to))throw Error('v4 M2 incompatible or already patched: '+file);
  staged.set(file,content.replace(from,to));
}
const commands=['domestic_dock_open','domestic_dock_bounds','domestic_dock_hide','domestic_dock_close'];
patch('src-tauri/src/lib.rs',
  '            domestic::domestic_api_chat,',
  ['            domestic::domestic_api_chat,',...commands.map(c=>'            domestic::'+c+',')].join('\n'));
patch('src-tauri/capabilities/default.json',
  '    "allow-domestic-api-chat"',
  ['    "allow-domestic-api-chat"',...commands.map(c=>'    "allow-'+c.replaceAll('_','-')+'"')].join(',\n'));
patch('src/host/index.ts',
  "    openMemberSlot: (provider: string, slot: number): Promise<void> => invoke('domestic_open_member', {provider,slot}),",
  [
    "    openMemberSlot: (provider: string, slot: number): Promise<void> => invoke('domestic_open_member', {provider,slot}),",
    "    dockOpen: (provider: string, slot: number, rect: DOMRectReadOnly): Promise<void> =>",
    "      invoke('domestic_dock_open',{provider,slot,bounds:toBounds(rect)}),",
    "    dockBounds: (provider: string, slot: number, rect: DOMRectReadOnly): Promise<void> =>",
    "      invoke('domestic_dock_bounds',{provider,slot,bounds:toBounds(rect)}),",
    "    dockHide: (provider: string, slot: number): Promise<void> => invoke('domestic_dock_hide',{provider,slot}),",
    "    dockClose: (provider: string, slot: number): Promise<void> => invoke('domestic_dock_close',{provider,slot}),",
  ].join('\n'));
const toCopy='src/ui/DomesticBrowserDock.tsx';
if(fs.existsSync(path.join(root,toCopy)))throw Error('Cannot overwrite existing embedded dock UI');
if(!fs.existsSync(path.join(overlay,toCopy)))throw Error('Missing v4 M2 UI overlay');
const native=fs.readFileSync(path.join(overlay,'src-tauri/src/domestic.rs'),'utf8');
for(const c of commands) if(!native.includes('pub async fn '+c+'('))throw Error('Missing Rust command '+c);
for(const [file,content] of staged)fs.writeFileSync(path.join(root,file),content,'utf8');
const destination=path.join(root,toCopy);
fs.mkdirSync(path.dirname(destination),{recursive:true});
fs.copyFileSync(path.join(overlay,toCopy),destination);
for(const c of commands) {
  const file=path.join(root,'src-tauri/permissions/autogenerated',c+'.toml');
  if(fs.existsSync(file))throw Error('Permission already exists: '+c);
  fs.mkdirSync(path.dirname(file),{recursive:true});
  fs.writeFileSync(file,'[[permission]]\nidentifier = "allow-'+c.replaceAll('_','-')+'"\ndescription = "Only the local control WebView may dock domestic provider pages"\ncommands.allow = ["'+c+'"]\n');
}
console.log('v4 M2 embedded real webpage dock applied, old data and original workflow retained.');
