import {existsSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash,createPrivateKey,createPublicKey,generateKeyPairSync,randomBytes} from 'node:crypto';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const privateDir=join(root,'.private');
const keysPath=join(privateDir,'test-owner-keys.json');
const devVarsPath=join(root,'.dev.vars');
const workbenchUserData=process.env.APPDATA?join(process.env.APPDATA,'DoubaoCreativeHubPublic'):'';
const marker='# Generated by DuduAI local-only V1.3 test setup. Never commit this file.';
const sha256=value=>createHash('sha256').update(value).digest('hex');

function verifyTestKeys(keys){
  const required=['DUDU_SIGNING_PRIVATE_PKCS8_B64','DUDU_LICENSE_PUBLIC_KEY_B64','DUDU_DEVICE_HMAC_KEY','DUDU_CARD_HMAC_KEY','DUDU_ADMIN_TOKEN','DUDU_ADMIN_TOKEN_SHA256'];
  if(!keys||required.some(key=>typeof keys[key]!=='string'||!keys[key])) throw Error('本机测试密钥文件不完整；为避免覆盖，已停止');
  let publicKey;
  try{
    const privateKey=createPrivateKey({key:Buffer.from(keys.DUDU_SIGNING_PRIVATE_PKCS8_B64,'base64'),format:'der',type:'pkcs8'});
    publicKey=createPublicKey(privateKey).export({format:'der',type:'spki'}).toString('base64');
  }catch{throw Error('本机测试签名私钥格式无效；未自动替换')}
  if(publicKey!==keys.DUDU_LICENSE_PUBLIC_KEY_B64) throw Error('本机测试签名公私钥不匹配');
  if(sha256(keys.DUDU_ADMIN_TOKEN)!==keys.DUDU_ADMIN_TOKEN_SHA256) throw Error('本机测试管理员令牌摘要不匹配');
  return keys;
}

function writeWorkbenchLocalConfig(keys){
  if(!workbenchUserData)return '';
  mkdirSync(workbenchUserData,{recursive:true});
  const file=join(workbenchUserData,'license-config.local.json');
  if(existsSync(file)){
    let current;
    try{current=JSON.parse(readFileSync(file,'utf8'))}catch{throw Error('现有工作台本机授权配置无法解析；为避免覆盖，已停止')}
    if(current.localTestMode!==true)throw Error('检测到非本机测试授权配置；未覆盖。请先确认 license-config.local.json 的用途');
  }
  const config={serviceUrl:'http://127.0.0.1:8788',publicKey:keys.DUDU_LICENSE_PUBLIC_KEY_B64,localTestMode:true};
  writeFileSync(file,JSON.stringify(config,null,2)+'\\n',{mode:0o600});
  return file;
}

export function ensureLocalTestSecrets(){
  mkdirSync(privateDir,{recursive:true,mode:0o700});
  let keys;
  if(existsSync(keysPath)){
    try{keys=verifyTestKeys(JSON.parse(readFileSync(keysPath,'utf8')))}
    catch(error){throw Error('现有本机测试密钥检查失败：'+error.message)}
  }else{
    const pair=generateKeyPairSync('ed25519');
    const token=randomBytes(32).toString('hex');
    keys={
      DUDU_SIGNING_PRIVATE_PKCS8_B64:pair.privateKey.export({type:'pkcs8',format:'der'}).toString('base64'),
      DUDU_LICENSE_PUBLIC_KEY_B64:pair.publicKey.export({type:'spki',format:'der'}).toString('base64'),
      DUDU_DEVICE_HMAC_KEY:randomBytes(48).toString('hex'),
      DUDU_CARD_HMAC_KEY:randomBytes(48).toString('hex'),
      DUDU_ADMIN_TOKEN:token,
      DUDU_ADMIN_TOKEN_SHA256:sha256(token)
    };
    writeFileSync(keysPath,JSON.stringify(keys,null,2)+'\n',{flag:'wx',mode:0o600});
  }
  const vars=[marker,
    'DUDU_SIGNING_PRIVATE_PKCS8_B64='+keys.DUDU_SIGNING_PRIVATE_PKCS8_B64,
    'DUDU_DEVICE_HMAC_KEY='+keys.DUDU_DEVICE_HMAC_KEY,
    'DUDU_CARD_HMAC_KEY='+keys.DUDU_CARD_HMAC_KEY,
    'DUDU_ADMIN_TOKEN_SHA256='+keys.DUDU_ADMIN_TOKEN_SHA256,
    'DUDU_LICENSE_PUBLIC_KEY_B64='+keys.DUDU_LICENSE_PUBLIC_KEY_B64
  ].join('\n')+'\n';
  if(existsSync(devVarsPath)){
    const existing=readFileSync(devVarsPath,'utf8');
    if(existing!==vars){
      if(existing.startsWith(marker)&&existing.includes('\\nDUDU_SIGNING_PRIVATE_PKCS8_B64=')){
        writeFileSync(devVarsPath,vars);
      }else{
        throw Error('现有 .dev.vars 与本机测试密钥不一致；为避免覆盖任何开发配置，已停止。请先自行备份并检查该文件');
      }
    }
  }else{
    writeFileSync(devVarsPath,vars,{flag:'wx',mode:0o600});
  }
  const workbenchConfigPath=writeWorkbenchLocalConfig(keys);
  return {keys,keysPath,devVarsPath,workbenchConfigPath};
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  try{
    const {keys,keysPath,devVarsPath,workbenchConfigPath}=ensureLocalTestSecrets();
    console.log('本机测试密钥已就绪（与生产密钥完全独立）：'+keysPath);
    console.log('Wrangler 本地变量已写入并受 Git 忽略：'+devVarsPath);
    if(workbenchConfigPath)console.log('独独AI工作台开发版已自动连接本机测试服务：'+workbenchConfigPath);
    else console.log('未检测到 APPDATA，未自动写入工作台本机测试配置。');
    console.log('本机测试管理员令牌（仅用于 127.0.0.1:8788，不要分享）：'+keys.DUDU_ADMIN_TOKEN);
  }catch(error){console.error('本机测试环境准备失败：'+error.message);process.exitCode=1}
}
